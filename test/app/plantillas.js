const { chromium } = require('playwright');
const ok = (c, m) => { console.log((c ? 'OK  ' : 'FAIL') + ' ' + m); if (!c) process.exitCode = 1; };
(async () => { const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined }); const p = await b.newPage({ viewport: { width: 390, height: 1100 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto(process.env.APP_URL); await p.waitForTimeout(900);
await p.evaluate(() => { S.onboarded = true; S.demo = false; S.lang = 'es'; S.routines = []; S.stack = []; tab('home'); go('routines'); }); await p.waitForTimeout(300);
let t = await p.evaluate(() => document.getElementById('m').innerText);
ok(/Empieza con una plantilla/.test(t) && (await p.locator('.vx-tpl').count()) === 3, 'estado vacío con 3 plantillas');
ok(await p.evaluate(() => vxTemplates.every(tp => tp[6].every(([n]) => EX.some(e => n instanceof RegExp ? n.test(e[0]) : e[0] === n)))), 'todos los ejercicios de las plantillas existen');
await p.screenshot({ path: 'shots/tpl.png' });
await p.click('text=Más plantillas'); await p.waitForTimeout(200);
ok((await p.locator('.vx-tpl').count()) === 5, 'ver más plantillas');
await p.click('.vx-tpl >> nth=0'); await p.waitForTimeout(300);
const r = await p.evaluate(() => S.routines.map(r => r.name + ':' + r.ex.length));
ok(r.length === 1 && /Cuerpo completo:6/.test(r[0]), 'un toque crea la rutina: ' + r);
t = await p.evaluate(() => document.getElementById('m').innerText);
ok(/Cuerpo completo/.test(t) && !/Empieza con una plantilla/.test(t), 'la lista muestra la rutina creada');
await p.evaluate(() => { startR(S.routines[0].id); }); await p.waitForTimeout(300);
ok(/Sentadilla/.test(await p.evaluate(() => document.getElementById('m').innerText)), 'se puede entrenar con ella al momento');
await p.evaluate(() => { S.routines = []; S.lang = 'en'; S.stack = []; tab('home'); go('routines'); }); await p.waitForTimeout(300);
ok(/Start with a template/.test(await p.evaluate(() => document.getElementById('m').innerText)), 'en inglés');
ok(errs.length === 0, 'sin errores JS ' + JSON.stringify(errs.slice(0, 3)));
await b.close(); })();
